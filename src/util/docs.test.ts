import { describe, expect, test } from 'vitest';
import { generateReferenceIndex } from './docs.ts';

describe(generateReferenceIndex, () => {
  test('renders normalized sections', () => {
    expect(
      generateReferenceIndex('React best practices', [
        {
          title: 'Eliminating Waterfalls',
          links: [
            {
              path: 'async-parallel.md',
              title: 'Parallelize Independent Work',
            },
          ],
        },
        {
          title: 'Bundle Size Optimization',
          links: [
            { path: 'bundle-direct-imports.md', title: 'Use Direct Imports' },
          ],
        },
      ])
    ).toBe(
      [
        '<!-- Generated by src/bin/ai-sync.ts. Do not edit manually. -->',
        '',
        '# React best practices index',
        '',
        'Load only relevant entries.',
        '',
        '## Eliminating Waterfalls',
        '',
        '- [Parallelize Independent Work](async-parallel.md)',
        '',
        '## Bundle Size Optimization',
        '',
        '- [Use Direct Imports](bundle-direct-imports.md)',
        '',
      ].join('\n')
    );
  });
});
